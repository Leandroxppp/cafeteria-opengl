// ============================================================
// MATERIAL DA CARCACA
// ============================================================

static void aplicarMaterialCarcaca() {

    GLfloat especular[] = {
        0.28f,
        0.28f,
        0.30f,
        1.0f
    };

    glMaterialfv(
        GL_FRONT_AND_BACK,
        GL_SPECULAR,
        especular
    );

    glMaterialf(
        GL_FRONT_AND_BACK,
        GL_SHININESS,
        30.0f
    );
}


// ============================================================
// MATERIAL METAL
// ============================================================

static void aplicarMaterialMetal() {

    GLfloat especular[] = {
        0.82f,
        0.82f,
        0.86f,
        1.0f
    };

    glMaterialfv(
        GL_FRONT_AND_BACK,
        GL_SPECULAR,
        especular
    );

    glMaterialf(
        GL_FRONT_AND_BACK,
        GL_SHININESS,
        85.0f
    );
}


// ============================================================
// MATERIAL DISPLAY
// ============================================================

