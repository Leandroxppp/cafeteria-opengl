void desenharPortaGuardanapos(
    float x,
    float y,
    float z
) {

    glPushMatrix();

    glTranslatef(
        x,
        y,
        z
    );


    // ========================================================
    // BASE DE MADEIRA
    // ========================================================

    desenharCaixa(
        0.0f,
        0.02f,
        0.0f,

        0.22f,
        0.04f,
        0.14f,

        0.22f,
        0.10f,
        0.04f
    );


    // ========================================================
    // SUPORTE ESQUERDO
    // ========================================================

    desenharCaixa(
        -0.09f,
         0.11f,
         0.0f,

         0.025f,
         0.18f,
         0.14f,

         0.26f,
         0.12f,
         0.05f
    );


    // ========================================================
    // SUPORTE DIREITO
    // ========================================================

    desenharCaixa(
         0.09f,
         0.11f,
         0.0f,

         0.025f,
         0.18f,
         0.14f,

         0.26f,
         0.12f,
         0.05f
    );


    // ========================================================
    // GUARDANAPOS
    // ========================================================

    desenharCaixa(
        0.0f,
        0.12f,
        0.0f,

        0.14f,
        0.15f,
        0.025f,

        0.95f,
        0.90f,
        0.78f
    );


    glPopMatrix();
}